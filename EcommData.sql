select * FROM consumer LIMIT 10;
---------------------------------------
-- Revenue / Sales 
-- Measuring overall business performance 
-- Analyzing growth, products, categories, regions, seasons, etc.
---------------------------------------

-- What share of total revenue does each category generate?
SELECT
    category,
    ROUND(SUM(purchase_amount_usd)::numeric, 2) AS revenue,
    ROUND(
        (100.0 * SUM(purchase_amount_usd)
         / SUM(SUM(purchase_amount_usd)) OVER ()
        )::numeric, 2
    ) AS revenue_percentage
FROM consumer
GROUP BY category
ORDER BY revenue DESC;
-- Clothing sells the most, making up 67.35% of the revenue percentage 

-- Which products generate the most revenue?
SELECT
    item_purchased,
    category,
    COUNT(*) AS number_of_purchases,
    ROUND(SUM(purchase_amount_usd)::numeric,2) AS revenue,
    ROUND(AVG(purchase_amount_usd)::numeric, 2) AS avg_purchase_amount
FROM consumer
GROUP BY item_purchased, category
ORDER BY revenue DESC;
-- From this we can see in order which items sold the best 

-- Which categories perform best in each season?
SELECT 
	season, 
	category, 
	ROUND(SUM(purchase_amount_usd)::numeric, 2) AS total_revenue, 
	COUNT(*) AS number_of_purchases
FROM consumer
GROUP BY season, category
ORDER BY season, total_revenue DESC; 
-- Clothing seems to perform the best in each season 


--Which states generate the most sales?
SELECT 
	location, 
	COUNT(*) AS number_of_purchases,
	ROUND(SUM(purchase_amount_usd)::numeric, 2) AS total_revenue,
	ROUND(AVG(purchase_amount_usd)::numeric, 2) AS avg_purchase_amount
FROM consumer 
GROUP BY location 
ORDER BY total_revenue DESC; 
--Calculating the amount of purchases and the total revenue from each state will help us with a more accurate analysis

-- How do sales vary across quarters?
SELECT 
	year_quarter, 
	ROUND(SUM(purchase_amount_usd)::numeric, 2) AS total_revenue 
FROM consumer
GROUP BY year_quarter
ORDER BY year_quarter;

-- What is the average revenue for each quarter across years?
WITH quarterly_sales AS (
	SELECT 
		purchase_year, 
		purchase_quarter, 
		SUM(purchase_amount_usd) AS revenue
	FROM consumer
	GROUP BY purchase_year, purchase_quarter
)

SELECT 
	purchase_quarter, 
	COUNT(*) AS years_obsered, 
	ROUND(AVG(revenue)::numeric, 2) AS avg_quarterly_revenue
FROM quarterly_sales
GROUP BY purchase_quarter
ORDER BY avg_quarterly_revenue DESC; 
--Typical revenue generated by each quarter 

--How does total revenue change from year to year?
WITH yearly_sales AS (
	SELECT purchase_year as year, SUM(purchase_amount_usd) as revenue 
	FROM consumer 
	GROUP BY purchase_year )
SELECT 
	year, 
	ROUND(revenue::numeric, 2) AS total_revenue, 
	ROUND (
			( 
				(revenue - LAG(revenue) OVER (ORDER BY year))
				/ NULLIF(LAG(revenue) OVER (ORDER BY year), 0)
				* 100
				)::numeric,
				2
			) AS revenue_growth_percentage
	FROM yearly_sales
	ORDER BY year;
-- Revenue grew by 20% in 2023 and 25% in 2024 

---------------------------------------
-- Customer Retention / Churn Rate 
-- Measures whether the company is keeping customers 
-- Allows us to investigate what characteristics are associated with churn 
---------------------------------------

-- Which age group spent the most on average? 
SELECT 
	age_group,
	COUNT(*) AS number_of_customers, 
	ROUND(SUM(purchase_amount_usd):: numeric, 2)
		AS total_revenue, 
	ROUND(AVG(purchase_amount_usd)::numeric, 2)
		AS avg_purchase_amount
FROM consumer
GROUP BY age_group
ORDER BY avg_purchase_amount DESC;
--The senior age group's average purchase amount was higher 
--However, the middle age group contributed the most to the total revenue

--Do subscribers spend more than non-subscribers?
SELECT
    subscription_status,
    COUNT(*) AS number_of_customers,
    ROUND(AVG(purchase_amount_usd)::numeric, 2) AS avg_purchase_amount,
    ROUND(SUM(purchase_amount_usd)::numeric, 2) AS total_revenue
FROM consumer
GROUP BY subscription_status
ORDER BY avg_purchase_amount DESC;
-- There are significantly more non-subscribers than subscribers
-- The average purchace amount is about the same for both subscribers and non-subscribers 
-- Non-subscribers contribute to the total revenue more since there are more of them

--Do customers who use promo codes have different spending patterns?
SELECT
    promo_code_used,
    COUNT(*) AS number_of_customers,
    ROUND(AVG(purchase_amount_usd)::numeric, 2)
        AS avg_purchase_amount,
    ROUND(SUM(purchase_amount_usd)::numeric, 2)
        AS total_revenue
FROM consumer
GROUP BY promo_code_used
ORDER BY avg_purchase_amount DESC;
-- Majority of cutomers did not use a promo code
-- The average purchase amount is the same for both segments 

--Does average spending differ by gender?
SELECT 
	gender,
	COUNT(*) AS number_of_customers,
    ROUND(AVG(purchase_amount_usd)::numeric, 2) AS avg_purchase_amount
FROM consumer
GROUP BY gender
ORDER BY avg_purchase_amount DESC; 
-- There are more male customers 
-- The average purchase amount of a female customer is slightly higher than the male customer. 

-- What percentage of customers are marked as churned?
SELECT
    churn,
    COUNT(*) AS number_of_customers,
    ROUND(
        100.0 * COUNT(*) / SUM(COUNT(*)) OVER (),
        2
    ) AS percentage
FROM consumer
GROUP BY churn
ORDER BY churn;
-- Majority of the customers did not churn (~93%)

--Which age groups have the highest churn rate?
SELECT
    age_group,
    COUNT(*) AS number_of_customers,
    SUM(CASE WHEN churn = 1 THEN 1 ELSE 0 END)
        AS churned_customers,
    ROUND(
        100.0 * SUM(CASE WHEN churn = 1 THEN 1 ELSE 0 END)
        / COUNT(*),
        2
    ) AS churn_rate
FROM consumer
GROUP BY age_group
ORDER BY churn_rate DESC;
-- Using a rate over a count gives us a more accurate representation of the churn rate 
--because one group might have more customers than the other
--Here we cab see that Young Adults have a higher churn rate 

-- Is churn different between subscibers and non-subscribers?
SELECT
    subscription_status,
    COUNT(*) AS number_of_customers,
    SUM(CASE WHEN churn = 1 THEN 1 ELSE 0 END)
        AS churned_customers,
    ROUND(
        100.0 * SUM(CASE WHEN churn = 1 THEN 1 ELSE 0 END)
        / COUNT(*),
        2
    ) AS churn_rate
FROM consumer
GROUP BY subscription_status
ORDER BY churn_rate DESC;
--Churn rate is about the same for both groups but slightly higher for subscribers 

-- Do promo code users have different churn rates?
SELECT
    promo_code_used,
    COUNT(*) AS number_of_customers,
    SUM(CASE WHEN churn = 1 THEN 1 ELSE 0 END)
        AS churned_customers,
    ROUND(
        100.0 * SUM(CASE WHEN churn = 1 THEN 1 ELSE 0 END)
        / COUNT(*),
        2
    ) AS churn_rate
FROM consumer
GROUP BY promo_code_used
ORDER BY churn_rate DESC;
--Non-promo code users have a slightly higher churn rate 

-- Which customer segments have both high spending and high churn?
SELECT
    age_group,
    subscription_status,
    COUNT(*) AS number_of_customers,
    ROUND(AVG(purchase_amount_usd)::numeric, 2)
        AS avg_purchase_amount,
    ROUND(
        100.0 * SUM(CASE WHEN churn = 1 THEN 1 ELSE 0 END)
        / COUNT(*),
        2
    ) AS churn_rate
FROM consumer
GROUP BY age_group, subscription_status
ORDER BY churn_rate DESC, avg_purchase_amount DESC;
-- Identifying each customer segment with Age Group and Subscription Status
--Comparing average purchase amount and churn rate 
--Young Adults who are subscribed spend an average of $51.68 and have a 12% churn rate

---------------------------------------
-- Customer Value and Satisfaction 
-- Identify products customers are most and least satisfied with
-- Invesigating whether satisfaction is associated with stronger sales performance
---------------------------------------

-- Do higher-rated categories also generate higher sales?
SELECT
    category,
    COUNT(*) AS number_of_purchases,
    ROUND(AVG(review_rating)::numeric, 2) AS avg_rating,
    ROUND(SUM(purchase_amount_usd)::numeric, 2) AS total_revenue,
    ROUND(AVG(purchase_amount_usd)::numeric, 2)
        AS avg_purchase_amount
FROM consumer
GROUP BY category
ORDER BY avg_rating DESC;
-- Shows the average number of reviews, ratings, and revenue of each category
-- Clothing generates the highest amount of revenue and has a good average rating 

-- Which products receive the highest average ratings?
SELECT
    item_purchased,
    category,
    COUNT(*) AS number_of_reviews,
    ROUND(AVG(review_rating)::numeric, 2)
        AS avg_rating
FROM consumer
GROUP BY item_purchased, category
ORDER BY avg_rating DESC;
--From this we can see which products are best selling and highly rated
-- Sweaters have the highest number of reviews and a higher average rating

-- Which items have the highest percentage of low ratings?
SELECT
	item_purchased,
    category,
    COUNT(*) AS number_of_reviews,
    SUM(CASE WHEN review_rating <= 2 THEN 1 ELSE 0 END)
        AS low_ratings,
    ROUND(
        100.0 * SUM(CASE WHEN review_rating <= 2 THEN 1 ELSE 0 END)
        / COUNT(*),
        2
    ) AS low_rating_percentage
FROM consumer
GROUP BY item_purchased, category
ORDER BY low_rating_percentage DESC;
-- Counting the number of reviews that were rated 2 or less since the average review is around 3.5 
-- Sweaters have the highest number of low ratings 
-- Sandals have the highest percentage of low ratings 

-- Do subscribers give higher ratings?
SELECT
    subscription_status,
    COUNT(*) AS number_of_reviews,
    ROUND(AVG(review_rating)::numeric, 2)
        AS avg_rating
FROM consumer
GROUP BY subscription_status
ORDER BY avg_rating DESC;
-- There is no major difference in the average rating but non-subscribers leave more reviews than subscribers 

-- Which customer segments have both high spending and high rating?
SELECT
    age_group,
    subscription_status,
    COUNT(*) AS number_of_customers,
	COUNT(review_rating) AS number_of_reviews,
    ROUND(AVG(purchase_amount_usd)::numeric, 2) AS avg_purchase_amount,
    ROUND(AVG(review_rating)::numeric, 2) AS avg_rating,
    ROUND(SUM(purchase_amount_usd)::numeric, 2) AS total_revenue
FROM consumer
GROUP BY
    age_group,
    subscription_status
ORDER BY
    avg_purchase_amount DESC,
    avg_rating DESC;
-- Middle-Aged non-subscribers generate the most total revenue 
-- They also leave the most amount of reviews and have a high average rating 


